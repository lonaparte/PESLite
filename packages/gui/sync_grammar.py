#!/usr/bin/env python3
"""Generate the browser parser's lexical constants from the native parser."""

from __future__ import annotations

import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "src/peslite/gui/preview/grammar.ts"


def render() -> str:
    """Return the generated TypeScript module."""
    sys.path.insert(0, str(ROOT / "src"))
    try:
        from peslite.assembly.syntax import (NAME_PATTERN, PARAMETER_DOMAINS, PATH_PATTERN,
                                             QUOTED_KEY_PATTERN)
    finally:
        sys.path.pop(0)
    domains = ", ".join(json.dumps(value) for value in PARAMETER_DOMAINS)
    return (
        "// Generated by packages/gui/sync_grammar.py; do not edit.\n"
        f"export const NAME = {json.dumps(NAME_PATTERN)};\n"
        f"export const PATH = {json.dumps(PATH_PATTERN)};\n"
        f"export const QUOTED_KEY = {json.dumps(QUOTED_KEY_PATTERN)};\n"
        f"export const PARAMETER_DOMAINS = new Set([{domains}]);\n"
    )


def main() -> int:
    TARGET.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
